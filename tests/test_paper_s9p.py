"""paper/numbers.tex carries the S9P values (group S9P of paper/make_figures.py, docs/stage9/SPEC.md section 15) that the
pure functions of analysis/stage9_pre.py compute from the committed results files.

Not one of the FP32 gates of scripts/gpu_stage9.sh (tests/test_stage9_pre.py is): paper/ is outside the code that the
stage-9 freeze guards, so numbers.tex may be regenerated after the freeze, and a renamed or reformatted macro must not stop
the GPU run. make_figures registers these macros straight from analysis/stage9_pre.py; this file checks the written file.
No model is loaded (about 30 s)."""
import re
import sys
from pathlib import Path

import pytest

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "analysis"))
import stage9_pre as P  # noqa: E402

K8 = {"mistral7": "MistralSeven", "llama8": "LlamaEight", "phi4": "PhiFour", "olmo7": "OlmoSeven", "falcon7": "FalconSeven",
      "gemma9": "GemmaNine", "qwen7": "QwenSeven", "qwen14": "QwenFourteen"}


def f2(x):
    return f"{x:.2f}"


def f3(x):
    return f"{x:.3f}"


@pytest.fixture(scope="module")
def A():
    mc = P.load_c(ROOT)
    return {"format_gap": P.format_gap(ROOT), "onset_curves": P.onset_curves(ROOT, mc), "edit_transfer": P.edit_transfer(ROOT),
            "binding_swap": P.binding_swap(ROOT), "dose": P.dose(ROOT, mc), "law": P.law_diagnostics(mc), "knockout": P.knockout(ROOT)}


@pytest.fixture(scope="module")
def tex():
    return dict(re.findall(r"\\newcommand\{\\(\w+)\}\{([^}]*)\}", (ROOT / "paper/numbers.tex").read_text()))


def test_numbers_tex_carries_the_recomputed_values(A, tex):
    """paper/numbers.tex (regenerated by paper/make_figures.py) carries the S9P values these functions compute."""
    for k, r in A["format_gap"].items():
        e = r["arms"]["AFTER"]["stale"]
        assert (tex[f"NpStaleAfter{K8[k]}"], tex[f"NpStaleAfter{K8[k]}Lo"], tex[f"NpStaleAfter{K8[k]}Hi"]) == tuple(f2(abs(x) if f2(x) == "-0.00" else x) for x in e)
    for k, r in A["onset_curves"].items():
        assert [tex[f"NpOnsetJointOpt{w}{K8[k]}"] for w in ("Three", "Seven", "Eleven", "Fifteen")] == [f2(x[0]) for x in r["flips"]["KV"]["P1"]]
    for k in ("qwen7", "mistral7"):
        assert tex[f"NpTauEfourbThree{K8[k]}"] == f2(A["onset_curves"][k]["tau_e4b_3"]["tau"])
    for k, r in A["dose"].items():
        assert tex[f"NpPsiKOptThreeFifty{K8[k]}"] == f2(r["psi"]["K", "P1", 3, 50][0])
    assert (tex["NpLawRhoCurve"], tex["NpLawRhoLogpk"], tex["NpLawRhoDiff"]) == (f3(A["law"]["rho_curve"]), f3(A["law"]["rho_logpk"]), f3(A["law"]["diff"]))
    assert tex["NpEditRho"] == f2(A["edit_transfer"]["rho"]) and tex["NpKoInitNoneMthreeMistralSeven"] == f2(A["knockout"]["mistral7"]["init"][0])
    assert tex["NpCopyValueMin"] == "0.04" and tex["NpCopyValueMax"] == "0.11" and tex["NpBindNamedMax"] == "0.01"
    assert not [n for n in tex if n.startswith("Np") and re.fullmatch(r"-0(\.0+)?", tex[n])], "a negative zero among the S9P macros"


def test_numbers_tex_binding_anchor(A, tex):
    """The binding-swap anchor is the printed IIA at the preregistered l* (SPEC 15.2 item 5), beside the best-block maximum."""
    b = A["binding_swap"]
    assert (tex["NpBindLstar"], tex["NpBindNoneLstar"]) == (str(b["none_lstar"][2]), b["none_lstar"][1]) == ("28", "0.99")
    assert tex["NpBindNoneMax"] == b["none"][1] == "1.00"
    assert tex["JcGsevenIIA"] == "0.993"   # the same anchor at 3 decimals (the stage-8c J-C-G7 line)


def test_macro_index_labels():
    """docs/stage9/S9P_MACROS.md: a range over printed score-file strings is labelled as a selection, not a recomputation."""
    md = (ROOT / "docs/stage9/S9P_MACROS.md").read_text()
    for n in ("NpPsgNomRatioMin", "NpPsgNomRatioMax"):
        line = next(x for x in md.splitlines() if x.startswith(f"| `\\{n}` |"))
        assert "[selects a printed string; label exploratory/post hoc]" in line and "recomputed" not in line, line
    line = next(x for x in md.splitlines() if x.startswith("| `\\NpBindNoneMax` |"))
    assert "post hoc best-block pick" in line and "NpBindNoneLstar" in line, line
